export function annotateText(text: string) {
  const terms = [...glosses].sort((a, b) => b.text.length - a.text.length);
  const chunks: { text: string; gloss?: Gloss }[] = [];
  let cursor = 0, plain = '';
  while (cursor < text.length) {
    const match = terms.find((term) => text.startsWith(term.text, cursor));
    if (match) {
      if (plain) chunks.push({ text: plain });
      plain = '';
      chunks.push({ text: match.text, gloss: match });
      cursor += match.text.length;
    } else { plain += text[cursor++]; }
  }
  if (plain) chunks.push({ text: plain });
  return chunks;
}
